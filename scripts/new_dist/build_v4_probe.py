"""Сборка диагностических образов v4 (2025-11-19, после 'все тесты -> 00000').

Контекст: все ранее собранные образы 2.22.3 дают «Внутренняя ошибка
микропрограммы 00000» — приложение 2.22.3 после запуска (0x37 OK) не отвечает
ПК. Анализ показал:
  - приложение 2.22.3 НЕ имеет собственного USB-стека: связь идёт через
    сервисы бутлоадера 0 (приём) / 1 (отправка) / 3 (тик) / 13 (регистрация),
    ровно как у стаба 2.22.3, который РАБОТАЕТ (0x33–0x37 отвечаются);
  - USB — поллинговый OTG_FS (0x50000000) внутри бутлоадера, прерывания не
    используются (v[35]/v[36] бутлоадера — заглушки «b .»);
  - приложение не переконфигурирует тактирование (нет записи RCC_CR/CFGR);
  - svc13-колбэк приложения (0x08017875) — пустышка «nop; bx lr», донорский
    бутлоадер его всё равно никогда не вызывает;
  - причина «00000» — внутри самого приложения (краш/зависание) ЛИБО в
    семантике сервисов нового поколения, ЛИБО в необеспеченных данных 0x8B.

Два новых ДИАГНОСТИЧЕСКИХ образа:

1) SM2Pro_full_flash_2.22.3_PROBE_stub_resident.bin
   Единственное отличие от patched_v2: в стабе 2.22.3 команда 0x37 (LAUNCH)
   больше НЕ переводит state=2 (NOP на «str r0, [r5]» @0x080045C) —
   приложение НЕ запускается, стаб остаётся жить и отвечает на ВСЕ команды:
   0x33–0x37 — штатно (0x37 вернёт {status=0} как «успех»!), остальное —
   статус 1 (штатный обработчик неизвестной команды 0x080042F8).
   СМЫСЛ: бисекция. Если ПК покажет ЛЮБУЮ ошибку кроме «00000» (например
   [0001]) — транспорт после «запуска» работает, и виновато именно
   приложение 2.22.3. Если снова «00000» — обмен после LAUNCH не доходит
   даже до стаба (проблема в smwin/sm2lib-логике, направление меняется).

2) SM2Pro_full_flash_2.22.3_MODE1.bin
   Единственное отличие от patched_v2: сервис 10 бутлоадера (режим платы)
   возвращает 1 вместо 2 («movs r1,#2» -> «movs r1,#1» @0x080012CE).
   Приложение 2.22.3 при режиме 1 использует другую таблицу пинов
   (0x08018338 вместо 0x080183C9) и другой таймерный контур (TIM1 вместо
   ADC-схемы). Гипотеза: клон пользователя — плата поколения 1, а донорский
   бутлоадер жёстко говорит «режим 2».

Оба строятся на базе SM2Pro_full_flash_2.22.3_patched_v2.bin (слоты 3–8 и
загрузочная запись уже исправлены — [0007] не вернётся).
"""
import hashlib
import struct
import sys

BASE = "/home/z/my-project/fw_analysis"
SRC = f"{BASE}/OUTPUT/SM2Pro_full_flash_2.22.3_patched_v2.bin"


def build(dst, patches, label):
    img = bytearray(open(SRC, "rb").read())
    assert len(img) == 0x40000, len(img)
    for off, expected, new, desc in patches:
        cur = bytes(img[off:off + len(expected)])
        if cur != expected:
            print(f"!! {label}: по смещению 0x{off:X} ожидалось {expected.hex()}, "
                  f"найдено {cur.hex()} — прерывание")
            sys.exit(1)
        img[off:off + len(new)] = new
        print(f"  {label}: 0x{off:08X}: {expected.hex(' ')} -> {new.hex(' ')}  ({desc})")
    with open(dst, "wb") as f:
        f.write(img)
    md5 = hashlib.md5(img).hexdigest()
    sha = hashlib.sha256(img).hexdigest()
    print(f"  {label}: {dst}")
    print(f"    MD5:    {md5}")
    print(f"    SHA256: {sha}\n")
    return md5, sha


if __name__ == "__main__":
    # --- 1) PROBE: стаб-резидент ---------------------------------------
    # 0x0800445C: str r0, [r5]  (28 60)  ->  nop (00 BF)
    # r5 = 0x20001400 (state стаба), r0 = 2. Без записи state остаётся 0,
    # цикл стаба никогда не уйдёт на запуск приложения (0x08004512).
    build(f"{BASE}/OUTPUT/SM2Pro_full_flash_2.22.3_PROBE_stub_resident.bin",
          [(0x445C, bytes.fromhex("2860"), bytes.fromhex("00BF"),
            "NOP: str r0,[r5] — 0x37 больше не запускает приложение")],
          "PROBE")

    # --- 2) MODE1: сервис 10 возвращает 1 -------------------------------
    # 0x080012CE: movs r1, #2 (02 21) -> movs r1, #1 (01 21)
    build(f"{BASE}/OUTPUT/SM2Pro_full_flash_2.22.3_MODE1.bin",
          [(0x12CE, bytes.fromhex("0221"), bytes.fromhex("0121"),
            "сервис 10 (режим платы): 2 -> 1")],
          "MODE1")
